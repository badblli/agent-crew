ROOT = Path(__file__).resolve().parents[2]
try:
    CONFIG = {"planDir": ".crew/plan", "stateDir": ".crew/state", "lead": "claude",
              **json.loads((ROOT / ".crew/config.json").read_text(encoding="utf-8"))}
    for key in ("planDir", "stateDir"):
        if not isinstance(CONFIG[key], str) or not CONFIG[key].strip():
            raise ValueError(f"{key} must be a nonempty path")
    PLAN = ROOT / CONFIG["planDir"]
    LEAD = ROOT / CONFIG["stateDir"]
    BOARD = LEAD / "board.json"
    TEAM = json.loads((PLAN / "team.json").read_text(encoding="utf-8"))
except (OSError, ValueError, TypeError) as exc:
    raise SystemExit(f"ERROR: config/plan: {exc}") from None
STEPS = [s["id"] for s in TEAM["steps"]]
AGENTS = {a["id"] for a in TEAM["agents"]}
GENERATED = "Generated by board.py — do not edit; agents do not read this file."


def spec_path(wp: str) -> Path:
    """Prefer the active spec, then search completed-WP archives deterministically."""
    if not re.fullmatch(r"[\w][\w.-]*", wp):
        raise SystemExit(f"invalid WP id: {wp}")
    active = PLAN / "wp" / f"{wp}.md"
    if active.is_file():
        return active
    return next(iter(sorted((PLAN / "wp" / "done").rglob(f"{wp}.md"))), active)


def headers(wp: str) -> dict:
    path = spec_path(wp)
    if not path.is_file():
        return {}
    return dict(line[2:].split(":", 1) for line in path.read_text(encoding="utf-8").splitlines()
                if line.startswith("- ") and ":" in line)


def cell(value: object) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")


def is_tracked(root: Path, path: Path) -> bool:
    return subprocess.run(["git", "-C", str(root), "ls-files", "--error-unmatch", "--",
                           str(path)], capture_output=True).returncode == 0


def archive(wp: str, worktree: Path | None = None) -> None:
    source = spec_path(wp)
    if worktree is None:
        # Match tell.sh: timestamp run directories, lexically newest first.
        runs = sorted(path for path in (LEAD / "runs" / wp).glob("2*") if path.is_dir())
        if runs and (runs[-1] / "workdir").is_file():
            value = (runs[-1] / "workdir").read_text(encoding="utf-8").strip()
            if value:
                worktree = Path(value)
    target = worktree.resolve() if worktree is not None else ROOT
    if not target.is_dir():
        raise SystemExit(f"missing worktree: {target}")
    dest = target / PLAN.relative_to(ROOT) / "wp" / "done" / datetime.now().strftime("%Y-%m") / f"{wp}.md"
    if target != ROOT:
        # Check before any mutations, including directory creation or main-copy deletion.
        if dest.exists():
            raise SystemExit(f"archive destination exists: {dest}")
        active = target / PLAN.relative_to(ROOT) / "wp" / f"{wp}.md"
        tracked = is_tracked(target, active)
        if not tracked and not source.is_file():
            raise SystemExit(f"missing WP spec: {wp}")
        main_tracked = is_tracked(ROOT, source) if source.is_file() else False
        meta = headers(wp)
        # The main spec may be absent until sync after merge; keep its summary before moving it.
        with _locked_board() as board:
            if wp in board["items"]:
                board["items"][wp]["summary"] = meta.get("Summary", meta.get("Özet", wp)).strip()
                _save(board)
        dest.parent.mkdir(parents=True, exist_ok=True)
        if tracked:
            subprocess.run(["git", "-C", str(target), "mv", "--", str(active), str(dest)], check=True)
        else:
            dest.write_bytes(source.read_bytes())
        if source.is_file() and source.parent == PLAN / "wp" and not main_tracked:
            source.unlink()
        return
    if not source.is_file():
        raise SystemExit(f"missing WP spec: {wp}")
    if source.parent != PLAN / "wp":
        return  # Already archived.
    if dest.exists():
        raise SystemExit(f"archive destination exists: {dest}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    tracked = is_tracked(ROOT, source)
    if tracked:
        subprocess.run(["git", "-C", str(ROOT), "mv", "--", str(source), str(dest)], check=True)
    else:
        source.rename(dest)


def wp_link(wp: str, parent: Path) -> str:
    target = quote(Path(os.path.relpath(spec_path(wp), parent)).as_posix(), safe="/.")
    return f"[`{wp}`]({target})"


def init_notes(templates: Path) -> None:
    """Only the explicit Obsidian choice creates vault files; preserve existing notes/settings."""
    if CONFIG.get("notes", "none") != "obsidian":
        return
    for name in ("index.md", "notes/README.md", ".obsidian/app.json"):
        dest = PLAN / name
        if dest.exists():
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if name == "index.md":
            text = (templates / name).read_text(encoding="utf-8")
            for target in ("rule.md", "feature.md", "docs/adr/"):
                relative = Path(os.path.relpath(ROOT / target, PLAN)).as_posix()
                text = text.replace("../../" + target, quote(relative, safe="/.") + ("/" if target.endswith("/") else ""))
            dest.write_text(text, encoding="utf-8")
        else:
            shutil.copyfile(templates / name, dest)
    ignore = ROOT / ".gitignore"
    rule = "/" + PLAN.relative_to(ROOT).as_posix() + "/.obsidian/workspace*.json"
    text = ignore.read_text(encoding="utf-8") if ignore.exists() else ""
    if rule not in text.splitlines():
        ignore.write_text(text + ("\n" if text and not text.endswith("\n") else "") + rule + "\n", encoding="utf-8")
    print("obsidian://open?path=" + quote(str(PLAN.resolve()), safe=""))


def doctor() -> None:
    errors = []
    warnings = []
    if CONFIG.get("notes", "none") not in ("none", "obsidian", "notion"):
        errors.append("config.notes must be none, obsidian or notion")
    engines = CONFIG.get("engines", ["codex"])
    if not isinstance(engines, list) or not engines or any(e not in ("codex", "claude", "agy") for e in engines):
        errors.append("config.engines must be a nonempty list of codex, claude or agy")
    if not PLAN.is_dir():
        errors.append(f"missing plan dir: {PLAN}")
    items = _load()["items"]
    for wp in items:
        try:
            path = spec_path(wp)
            if not path.is_file():
                errors.append(f"missing WP file: {wp}")
        except SystemExit:
            errors.append(f"invalid WP id: {wp}")
    for path in sorted((PLAN / "wp").rglob("*")):
        if not path.is_file() or path.name == "TEMPLATE.md":
            continue
        if path.stem not in items and "done" not in path.relative_to(PLAN / "wp").parts[:-1]:
            warnings.append(f"stray WP file: {path.relative_to(PLAN).as_posix()}")
        if path.suffix == ".md":
            try:
                meta = dict(line[2:].split(":", 1) for line in path.read_text(encoding="utf-8").splitlines()
                            if line.startswith("- ") and ":" in line)
                if not any(meta.get(key, "").strip() for key in ("Summary", "Özet")):
                    errors.append(f"WP headers: missing Summary: {path.relative_to(PLAN).as_posix()}")
                if "Model" in meta and meta["Model"].strip() not in ("light", "standard", "deep", "peak"):
                    errors.append(f"WP headers: invalid Model: {path.relative_to(PLAN).as_posix()}")
                if meta.get("Engine", "codex").strip() not in ("codex", "claude", "agy"):
                    errors.append(f"WP headers: invalid Engine: {path.relative_to(PLAN).as_posix()}")
            except (OSError, ValueError, SystemExit):
                errors.append(f"WP headers cannot parse: {path.relative_to(PLAN).as_posix()}")
    for name in ("index.md", "plan.md"):
        path = PLAN / name
        if not path.exists():
            continue  # Optional index; local views may be absent in a fresh clone.
        for target in re.findall(r"\[[^\]\n]*\]\(([^)]+)\)", path.read_text(encoding="utf-8")):
            url = urlsplit(target.strip("<>"))
            if url.scheme or url.netloc or not url.path:
                continue
            destination = (path.parent / unquote(url.path)).resolve()
            # Views and the session card are created locally after cloning or planning.
            optional = {(PLAN / name).resolve() for name in
                        ("plan.md", "history.md", "history", "handoff.md")}
            if not destination.exists() and destination not in optional:
                errors.append(f"broken link in {name}: {target}")
    result = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], capture_output=True)
    if result.returncode:
        errors.append("cannot inspect tracked files with git ls-files")
    else:
        prefix = PLAN.relative_to(ROOT).as_posix() + "/.obsidian/"
        for name in result.stdout.decode("utf-8").split("\0"):
            if name.startswith(prefix) and re.fullmatch(r"workspace[^/]*\.json", name[len(prefix):]):
                errors.append(f"tracked workspace file: {name}")
    for warning in warnings:
        print("WARN: " + warning)
    for error in errors:
        print("ERROR: " + error)
    if errors:
        raise SystemExit(1)
    print("OK: config, plan, WP headers, links and workspace files")


def history_entries(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [line for line in path.read_text(encoding="utf-8").splitlines()
            if re.match(r"^- \d{4}-\d{2}-\d{2} \| (?:`[^`]+`|\[`[^`]+`\]\([^)]+\)) \|", line)]


def write_history(path: Path, entries: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED + "\n\n" + "\n".join(re.sub(r"(?<=\| )(?:\[)?`([^`]+)`(?:\]\([^)]+\))?", lambda m: wp_link(m[1], path.parent), entry, count=1)
                            for entry in entries) + "\n", encoding="utf-8")


def views() -> None:
    with _locked_board() as board:
        _write_views(board)


def _write_views(board: dict) -> None:
    PLAN.mkdir(parents=True, exist_ok=True)
    lines = [GENERATED, "", "| WP | Summary | Agent | Step | Engine/tier | Depends on |",
             "| --- | --- | --- | --- | --- | --- |"]
    for wp, item in board["items"].items():
        if item.get("step") == "merged":
            continue
        meta = headers(wp)
        summary = meta.get("Summary", meta.get("Özet", item.get("summary", wp))).strip()
        roster = next((a for a in TEAM["agents"] if a["id"] == item.get("agent")), {})
        enabled = CONFIG.get("engines", ["codex"])
        default_engine = roster.get("engine") if roster.get("engine") in enabled else enabled[0]
        values = [wp_link(wp, PLAN), summary, display_name(item.get("agent", "")), item.get("step", ""),
                  meta.get("Engine", default_engine).strip() + "/" + meta.get("Model", "standard").strip(),
                  meta.get("Depends on", "none").strip()]
        lines.append("| " + " | ".join(cell(v) for v in values) + " |")
    (PLAN / "plan.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    current = history_entries(PLAN / "history.md")
    archived = [entry for path in sorted((PLAN / "history").glob("*.md"))
                for entry in history_entries(path)]
    known = {entry.split("`", 2)[1] for entry in current + archived}
    added = []
    for wp, item in board["items"].items():
        if item.get("step") != "merged" or wp in known:
            continue
        meta = headers(wp)
        date = item.get("merged_at", datetime.now().isoformat())
        summary = meta.get("Summary", meta.get("Özet", item.get("summary", wp))).strip()
        pr = item.get("pr_url") or item.get("pr") or meta.get("PR", "").strip()
        if not pr:
            match = re.search(r"https?://\S+/pull/\d+", item.get("note", ""))
            pr = match.group() if match else ""
        added.append((date, f"- {date[:10]} | `{wp}` | {cell(summary)} | {cell(pr)}"))
        known.add(wp)
    for path in sorted((PLAN / "wp" / "done").glob("????-??/*.md")):
        month, wp = path.parent.name, path.stem
        if wp in known or not re.fullmatch(r"\d{4}-(0[1-9]|1[0-2])", month):
            continue
        meta = headers(wp)
        summary = meta.get("Summary", meta.get("Özet", wp)).strip()
        date = month + "-01"
        added.append((date, f"- {date} | `{wp}` | {cell(summary)} | "))
        known.add(wp)
    # Backfilled archives may predate existing local entries. Keep both in date order.
    entries = sorted([entry for _, entry in sorted(added, reverse=True)] + current,
                     key=lambda entry: entry[2:12], reverse=True)
    write_history(PLAN / "history.md", entries[:30])
    for year in sorted({entry[2:6] for entry in entries[30:] + archived}):
        path = PLAN / "history" / f"{year}.md"
        write_history(path, sorted([entry for entry in entries[30:] if entry[2:6] == year]
                                  + history_entries(path), key=lambda entry: entry[2:12], reverse=True))


def lead(next_lead: str | None = None) -> str:
    if next_lead is None:
        return _load().get("lead", {}).get("id", CONFIG["lead"])
    if next_lead not in ("claude", "codex"):
        raise SystemExit("usage: board.py lead [claude|codex]")
    if next_lead == "codex" and "codex" not in CONFIG.get("engines", []):
        raise SystemExit("Codex fallback requires codex in config.engines")
    with _locked_board() as board:
        if next_lead != board.get("lead", {}).get("id"):
            board["lead"] = {"id": next_lead, "since": datetime.now().astimezone().isoformat(timespec="seconds")}
            _save(board)
    return next_lead


def handoff(next_lead: str | None = None) -> str:
    current = lead(next_lead)
    board = _load()
    lines = ["# Handoff", "", "Phase: " + cell(board.get("phase", "")),
             "Focus: " + cell(board.get("focus", "")), "", "## Lead", current]
    if current == "codex" and CONFIG["lead"] == "claude":
        lines.append('codex "Use the crew-lead skill as fallback lead: read .crew/plan/handoff.md and continue."')
        if CONFIG["planDir"] != ".crew/plan":
            lines.append("Configured handoff: " + cell(CONFIG["planDir"]) + "/handoff.md (read this card).")
    lines.extend(["", "## Open WPs"])
    opened = [(wp, item) for wp, item in board["items"].items() if item.get("step") != "merged"]
    # Leave room for the decision and the lead's Next section, even on large boards.
    lines.extend(f"- {cell(wp)}: {cell(item.get('step', ''))}" for wp, item in opened[:20])
    if len(opened) > 20:
        lines.append(f"- … {len(opened) - 20} more open WPs (board.py views)")
    lines.extend(["", "## Open decision", open_question(), "", "## Next", "- <lead: next action>"])
    PLAN.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    (PLAN / "handoff.md").write_text(text, encoding="utf-8")
    return text


def _load(*, strict: bool = False) -> dict:
    try:
        return json.loads(BOARD.read_text(encoding="utf-8"))
    except FileNotFoundError:
        pass
    except (OSError, ValueError):
        if strict:
            raise
    return {"phase": "", "focus": "", "items": {}}


@contextmanager
def _locked_board():
    """Serialize board read-modify-write operations and their generated views."""
    LEAD.mkdir(parents=True, exist_ok=True)
    # Keep a separate file with a stable identity while board.json is replaced.
    with BOARD.with_suffix(".lock").open("a+b") as lock:
        if os.name == "nt":
            import msvcrt

            lock.seek(0)
            deadline = time.monotonic() + 10
            while True:
                try:
                    msvcrt.locking(lock.fileno(), msvcrt.LK_NBLCK, 1)
                    break
                except OSError as exc:
                    if exc.errno != errno.EACCES or time.monotonic() >= deadline:
                        raise
                    time.sleep(0.02)
            try:
                yield _load(strict=True)
            finally:
                msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl

            fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
            yield _load(strict=True)


def _save(board: dict) -> None:
    LEAD.mkdir(exist_ok=True)
    tmp = BOARD.with_suffix(".tmp")
    tmp.write_text(json.dumps(board, ensure_ascii=False, indent=2), encoding="utf-8")
    deadline = time.monotonic() + 2
    while True:
        try:
            tmp.replace(BOARD)
            return
        except PermissionError:
            # Windows readers can briefly block replacement of board.json.
            if os.name != "nt" or time.monotonic() >= deadline:
                raise
            time.sleep(0.02)


def say(wp: str, sender: str, text: str, kind: str = "message") -> None:
    text = text.strip()
    if not text:
        return
    chat = LEAD / "chat"
    chat.mkdir(parents=True, exist_ok=True)
    entry = {"ts": int(time.time() * 1000), "from": sender, "kind": kind, "text": text}
    with (chat / f"{wp}.jsonl").open("a", encoding="utf-8") as out:
        out.write(json.dumps(entry, ensure_ascii=False) + "\n")


def display_name(agent_id: str) -> str:
    """The agent's name in the active theme (team.json "theme"), else its plain name, else the id."""
    theme = TEAM.get("themes", {}).get(TEAM.get("theme", ""), {})
    themed = theme.get("agents", {}).get(agent_id, {}).get("name")
    plain = next((a.get("name") for a in TEAM.get("agents", []) if a.get("id") == agent_id), None)
    return themed or plain or agent_id


def agent_of(wp: str) -> str:
    return _load()["items"].get(wp, {}).get("agent", "")


def open_question() -> str:
    path = LEAD / "decision.json"
    decision = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    return cell(decision.get("question", "none")) if decision.get("status") == "open" else "none"


def worker_route(spec: str, agent: str, default_tier: str, current_lead: str) -> tuple[str, str, str]:
    def field(name: str, default: str) -> str:
        match = re.search(rf"^- {name}:[ \t]*(\S+)", spec, re.MULTILINE)
        return match[1].lower() if match else default

    enabled = CONFIG.get("engines", ["codex"])
    roster_engine = next((a.get("engine") for a in TEAM["agents"] if a["id"] == agent), None)
    default_engine = roster_engine if roster_engine in enabled else enabled[0]
    forced = os.environ.get("CREW_ENGINE_FORCE", "").lower()
    engine = forced or field("Engine", os.environ.get("CREW_ENGINE", "").lower() or default_engine)
    notice = ""
    if engine == "claude" and current_lead == "codex":
        if CONFIG["lead"] == "claude" and not forced:
            engine = "codex"
            notice = "Codex fallback lead: routing Claude work to Codex (shared Claude quota)."
        elif CONFIG["lead"] == "codex" and "claude" not in enabled:
            engine = "codex"
            notice = "Codex lead: Claude workers require claude in config.engines."
    return engine, field("Model", default_tier), notice


def status() -> str:
    board = _load()
    current = board.get("lead", {}).get("id", CONFIG["lead"])
    lines = [f"Phase: {cell(board.get('phase') or '—')} | Focus: {cell(board.get('focus') or '—')}",
             f"Lead: {current}", f"Open decision: {open_question()}", "Open WPs:"]
    opened = [(wp, item) for wp, item in board["items"].items() if item.get("step") != "merged"]
    limit = 30 - len(lines)
    visible = opened[:limit - 1] if len(opened) > limit else opened
    if visible:
        models = PLAN / "models.json"
        tier_default = json.loads(models.read_text(encoding="utf-8"))["default"] if models.exists() else "—"
        for wp, item in visible:
            path = spec_path(wp)
            spec = path.read_text(encoding="utf-8") if path.is_file() else ""
            agent = item.get("agent") or ""
            engine, tier, _ = worker_route(spec, agent, tier_default, current)
            lines.append(f"- {cell(wp)} | {cell(display_name(agent) or 'unassigned')} | "
                         f"{cell(item.get('step') or '—')} | {cell(engine)}/{cell(tier)}")
    else:
        lines.append("- none")
    if len(opened) > len(visible):
        lines.append(f"- … {len(opened) - len(visible)} more open WPs")
    return "\n".join(lines)


def step(wp: str, step_id: str, note: str = "") -> None:
    if step_id not in STEPS and step_id != "failed":
        raise SystemExit(f"unknown step {step_id}; one of {STEPS + ['failed']}")
    with _locked_board() as board:
        item = board["items"].setdefault(wp, {})
        item["step"] = step_id
        if step_id == "merged":
            item.setdefault("merged_at", datetime.now().isoformat())
        if note:
            item["note"] = note
        _save(board)
        if note:
            say(wp, "claude", note, "note")
        _write_views(board)


def session(wp: str, command: str) -> None:
    with _locked_board() as board:
        item = board["items"].setdefault(wp, {})
        if item.get("session") == command:
            return
        item["session"] = command
        item["note"] = "open: " + command
        _save(board)
        say(wp, "claude", "open: " + command, "note")


def ingest(wp: str, run: Path | None) -> None:
    sender = agent_of(wp) or "agent"
    quota_notified = bool(run and (run / "quota_notified").exists())
    for line in sys.stdin:
        try:
            event = json.loads(line)
        except ValueError:
            continue  # Hook stdout can contain non-JSON text.
        if not isinstance(event, dict):
            continue
        # Stable compact JSON also supports the existing shell failure/thread extractors.
        print(json.dumps(event, ensure_ascii=False, separators=(",", ":")), flush=True)
        kind = event.get("type")
        if run and event.get("session_id"):
            thread = str(event["session_id"])
            (run / "thread").write_text(thread + "\n", encoding="utf-8")
            session(wp, f"claude --resume {thread}")
        item = event.get("item") or {}
        if kind == "assistant":
            for content in (event.get("message") or {}).get("content", []):
                if content.get("type") == "text":
                    say(wp, sender, content.get("text", ""))
        elif kind == "result":
            success = event.get("subtype") == "success" and not event.get("is_error", False)
            text = event.get("result") or "\n".join(event.get("errors") or [])
            if run:
                (run / "report.md").write_text(text, encoding="utf-8")
                (run / "result_status").write_text("success" if success else "error", encoding="utf-8")
            if not success:
                say(wp, sender, text or str(event.get("subtype", "error")), "error")
        elif kind == "rate_limit_event":
            hint = event.get("rate_limit_info") or {}
            if run:
                (run / "rate_limit.json").write_text(json.dumps(hint), encoding="utf-8")
            usage = LEAD / "usage"
            usage.mkdir(parents=True, exist_ok=True)
            (usage / "claude-workers.json").write_text(
                json.dumps({"wp": wp, "updated_at": int(time.time()), "rate_limit_info": hint}),
                encoding="utf-8")
            utilization = hint.get("utilization")
            limited = (hint.get("status", "allowed") != "allowed"
                       or isinstance(utilization, (int, float)) and utilization >= 1)
            if limited and not quota_notified:
                say(wp, sender, "Claude quota: " + json.dumps(hint), "note")
                quota_notified = True
                if run:
                    (run / "quota_notified").write_text("notified\n", encoding="utf-8")
        elif kind == "item.completed" and item.get("type") == "agent_message":
            say(wp, sender, item.get("text", ""))
        elif kind == "turn.failed":
            say(wp, sender, "Hata: " + str((event.get("error") or {}).get("message", "")), "error")
        elif event.get("event") == "result":
            res = event.get("result") or {}
            if res.get("status") == "SUCCESS":
                say(wp, sender, res.get("response", ""))
            else:
                say(wp, sender, "Hata: " + str(res.get("status", "")), "error")


def main(argv: list[str]) -> None:
    if len(argv) < 2:
        raise SystemExit(__doc__)
    cmd, args = argv[1], argv[2:]
    if cmd == "phase":
        with _locked_board() as board:
            board["phase"], board["focus"] = args[0], args[1] if len(args) > 1 else ""
            _save(board)
    elif cmd == "assign":
        wp, agent = args
        if agent not in AGENTS:
            raise SystemExit(f"unknown agent {agent}; one of {sorted(AGENTS)}")
        spec = spec_path(wp).read_text(encoding="utf-8")
        summary = next((ln.split(":", 1)[1].strip() for ln in spec.splitlines()
                        if ln.startswith(("- Summary:", "- Özet:"))), wp)
        with _locked_board() as board:
            board["items"].setdefault(wp, {}).update(agent=agent, step="assigned")
            _save(board)
            say(wp, "claude", ("Görev: " if CONFIG.get("lang") == "tr" else "Task: ") + summary, "assign")
            _write_views(board)
    elif cmd == "step":
        step(args[0], args[1], args[2] if len(args) > 2 else "")
    elif cmd == "paths":
        print(PLAN.as_posix(), LEAD.as_posix())
    elif cmd == "archive":
        if len(args) == 1:
            archive(args[0])
        elif len(args) == 3 and args[1] == "--worktree":
            archive(args[0], Path(args[2]))
        else:
            raise SystemExit("usage: board.py archive <wp> [--worktree <dir>]")
    elif cmd == "doctor":
        doctor()
    elif cmd == "init-notes":
        init_notes(Path(args[0]))
    elif cmd == "views":
        views()
    elif cmd == "handoff":
        if not args:
            print(handoff(), end="")
        elif len(args) == 2 and args[0] == "--to" and args[1] in ("codex", "claude"):
            print(handoff(args[1]), end="")
        else:
            raise SystemExit("usage: board.py handoff [--to codex|claude]")
    elif cmd == "lead":
        if len(args) > 1:
            raise SystemExit("usage: board.py lead [claude|codex]")
        print(lead(args[0] if args else None))
    elif cmd == "status":
        print(status())
    elif cmd == "model":
        routing = json.loads((PLAN / "models.json").read_text(encoding="utf-8"))
        spec = spec_path(args[0]).read_text(encoding="utf-8")
        engine, tier, notice = worker_route(spec, agent_of(args[0]), routing["default"], lead())
        if notice:
            if os.environ.get("CREW_ENGINE_FORCE"):
                raise SystemExit(notice)
            print(notice, file=sys.stderr)

        tiers_key = f"{engine}_tiers" if engine != "codex" else "tiers"
        if tiers_key not in routing or tier not in routing[tiers_key]:
            raise SystemExit(f"unknown engine/tier {engine}/{tier}; check models.json")

        print(routing[tiers_key][tier]["model"], routing[tiers_key][tier].get("effort", "medium"), tier, engine)
    elif cmd == "agent":
        print(agent_of(args[0]))
    elif cmd == "name":
        print(display_name(args[0]))
    elif cmd == "say":
        say(args[0], args[1], args[2])
    elif cmd == "session":
        session(args[0], args[1])
    elif cmd == "ingest":
        ingest(args[0], Path(args[1]) if len(args) > 1 else None)
    elif cmd == "decide":
        path = LEAD / "decision.json"
        if args == ["--clear"]:
            path.unlink(missing_ok=True)
            return
        options = []
        for raw in args[1:]:
            label, _, detail = raw.partition("|")
            options.append({"label": label.strip(), "detail": detail.strip()})
        decision = {"id": str(int(time.time() * 1000)), "question": args[0], "options": options, "status": "open"}
        LEAD.mkdir(exist_ok=True)
        path.write_text(json.dumps(decision, ensure_ascii=False, indent=2), encoding="utf-8")
    elif cmd == "report":
        wp, path = args
        text = Path(path).read_text(encoding="utf-8") if Path(path).exists() else ""
        summary = text.split("## Summary", 1)[-1].split("\n## ", 1)[0].strip() if "## Summary" in text else text[:600]
        say(wp, agent_of(wp) or "codex", "Rapor: " + summary, "report")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stdin.reconfigure(encoding="utf-8")
    main(sys.argv)
